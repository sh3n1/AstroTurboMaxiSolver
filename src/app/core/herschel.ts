// William Herschel's discoveries: the Herschel 400, chosen by the Ancient City Astronomy
// Club about 1980, and the Herschel II, chosen by the Rose City Astronomers in 1997, as the
// Astronomical League's observing programmes use them. The numbers are facts; the credit
// for both selections is in Settings.
//
// The objects are shown with the app's own catalogue designations, so the numbers follow
// the app's data:
// - M76 is NGC 650 here, though the Herschel 400 lists it as NGC 651, its other half.
// - NGC 4665 is NGC 4664 here, which OpenNGC treats as the same galaxy.
// - NGC 2371 and NGC 2372, one planetary nebula, are a single object in the data, and so
//   are NGC 6882 and NGC 6885, two overlapping clusters. Each still gets a row per number.
// - NGC 206, a star cloud inside M31 in the Herschel II, isn't in OpenNGC, so the app
//   adds it itself, in extra-targets.ts.
// - The Herschel II has the League's later swap: NGC 1985, 4517 and 7492 in place of NGC
//   1750, 1990 and 2253.

